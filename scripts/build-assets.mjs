// Generates icon and illustration modules from design/ (exported from Figma).
// Icons: 20x20, single path, fill = currentColor. Illustrations: Figma light colours
// are swapped for the illustration tokens so they follow light and dark mode.
// Run: npm run assets
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
const root = new URL("../", import.meta.url);
const read = (p) => readFileSync(new URL(p, root), "utf8");

const icons = { ...JSON.parse(read("design/icons-a.json")), ...JSON.parse(read("design/icons-b.json")) };
const names = Object.keys(icons).sort();
let ts = "// Generated by scripts/build-assets.mjs. Do not edit by hand.\n\n";
ts += `export const iconNames = ${JSON.stringify(names)} as const;\nexport type IconName = (typeof iconNames)[number];\n\n`;
ts += "export const iconPaths: Record<IconName, { x: number; y: number; d: string }> = {\n";
for (const n of names) { const [x, y, d] = icons[n]; ts += `  ${JSON.stringify(n)}: { x: ${x}, y: ${y}, d: ${JSON.stringify(d)} },\n`; }
ts += "};\n";
mkdirSync(new URL("src/components/icon/", root), { recursive: true });
writeFileSync(new URL("src/components/icon/paths.ts", root), ts);

const map = { "#0a0a0a": "var(--illustration-line)", "#ffffff": "var(--illustration-fill)", white: "var(--illustration-fill)", "#e6e6e6": "var(--illustration-shade)" };
const ill = {};
for (const f of readdirSync(new URL("design/illustrations/", root)).filter((f) => f.endsWith(".svg")).sort()) {
  let svg = read("design/illustrations/" + f);
  const vb = svg.match(/viewBox="([^"]+)"/)[1];
  let inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/\n/g, "");
  inner = inner.replace(/(fill|stroke)="(#[0-9a-fA-F]{6}|white)"/g, (m, a, c) => {
    const v = map[c.toLowerCase()];
    if (!v) throw new Error(`${f}: unmapped colour ${c}`);
    return `${a}="${v}"`;
  });
  ill[f.replace(/\.svg$/, "")] = { viewBox: vb, svg: inner };
}
let it = "// Generated by scripts/build-assets.mjs. Do not edit by hand.\n\n";
it += `export const illustrations = ${JSON.stringify(ill, null, 0)} as const;\nexport type IllustrationName = keyof typeof illustrations;\n`;
mkdirSync(new URL("src/components/illustration/", root), { recursive: true });
writeFileSync(new URL("src/components/illustration/data.ts", root), it);
console.log(`${names.length} icons, ${Object.keys(ill).length} illustrations`);
