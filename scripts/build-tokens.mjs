// Generates src/styles/tokens.css from design/tokens.json (exported from Figma variables).
// Run: npm run tokens
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
const t = JSON.parse(readFileSync(new URL("../design/tokens.json", import.meta.url)));
const v = (n) => "--" + n.replace(/\//g, "-");
let css = "/* Generated by scripts/build-tokens.mjs from design/tokens.json. Do not edit by hand. */\n\n:root {\n";
for (const [n, hex] of Object.entries(t.primitives)) css += `  ${v(n)}: ${hex};\n`;
css += "}\n\n:root, [data-theme=\"light\"] {\n  color-scheme: light;\n";
for (const [n, [l]] of Object.entries(t.semantic)) css += `  ${v(n)}: var(${v(l)});\n`;
css += "}\n\n[data-theme=\"dark\"] {\n  color-scheme: dark;\n";
for (const [n, [, d]] of Object.entries(t.semantic)) css += `  ${v(n)}: var(${v(d)});\n`;
css += "}\n\n@media (prefers-color-scheme: dark) {\n  [data-theme=\"system\"] {\n    color-scheme: dark;\n";
for (const [n, [, d]] of Object.entries(t.semantic)) css += `    ${v(n)}: var(${v(d)});\n`;
css += "  }\n}\n\n/* Tailwind theme: semantic colours only, so screens never use primitives. */\n@theme inline {\n";
for (const n of Object.keys(t.semantic)) css += `  --color-${n.replace(/\//g, "-")}: var(${v(n)});\n`;
for (const [n, size, w, lh, ls] of t.text) css += `  --text-${n}: ${size}px;\n  --text-${n}--line-height: ${lh};\n  --text-${n}--letter-spacing: ${ls}em;\n  --text-${n}--font-weight: ${w};\n`;
css += "}\n";
mkdirSync(new URL("../src/styles/", import.meta.url), { recursive: true });
writeFileSync(new URL("../src/styles/tokens.css", import.meta.url), css);
console.log("tokens.css written");
